#!/usr/bin/env python3
"""List every KFG cord whose Value column is not the sum of its knot tokens (the `valueConflict` field
written by scripts/build_data.py), with the OKR reading where the OKR has the cord, as a Markdown table for
reporting upstream to the Khipu Field Guide.

Run:  python3 scripts/mk/value_knot_conflicts.py  ->  scripts/mk/value_knot_conflicts.md
"""

from __future__ import annotations

import glob
import json
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import build_data as bd  # noqa: E402

CAUSES = {
    "reordered": "rows reordered, Value column not moved with them (the stored values form a cycle over "
                 "neighbouring cords' knots)",
    "logged-edit": "the ChangeLog records an edit to this cord's value or knots that reached only one of the two",
    "knot-token": "one knot token's value disagrees with its own notation (count x place, long-knot turns, "
                  "E = 1, TF = 1); read by its notation, the knots give the stored value",
    "zero-value": "Value is 0 although knots are recorded",
    "no-knots": "a value with no knots recorded",
    "unexplained": "none of the above; likely a Value-column slip (the OKR reading is given where it exists)",
}


def main() -> None:
    okr = bd.OkrCorpus()
    rows, causes = [], Counter()
    for p in sorted(glob.glob(os.path.join(bd.OUT_DIR, "khipus", "KH*.json"))):
        k = json.load(open(p))
        flagged = [c for c in k["cords"] if c.get("valueConflict")]
        if not flagged:
            continue
        rec = okr.khipu(k["id"])
        oc = {c["name"]: c for c in (rec["cords"] if rec else [])}
        for c in flagged:
            v = c["valueConflict"]
            causes[v["cause"]] += 1
            o = oc.get(c["name"])
            knots = ";".join(bd.knot_string(x) for x in c["knots"]) or "-"
            rows.append(f"| {k['id']} | {c['name']} | {c['value']} | {v['knots']} | "
                        f"{o['value'] if o else '-'} | `{knots}` | {v['cause']} | {v['note'].replace('|', '/')} |")
    out = [
        "# KFG cords whose Value is not the sum of their knots",
        "",
        "Generated by `scripts/mk/value_knot_conflicts.py` from the `valueConflict` field that",
        "`scripts/build_data.py` writes on each such cord. Both numbers are the KFG's own: `Value` is the",
        "Cords sheet's Value column, `knots` the sum of the `,value` part of each knot token in the Knots column.",
        "Our parser reads both verbatim (no ETL bug found); the app keeps `value` as published and marks the cord.",
        "`OKR` is the Open Khipu Repository reading of the same cord name (knot_value_type sum), `-` when the OKR",
        "has no such cord. Note the OKR is the KFG's ancestor, so agreement with it is not independent evidence.",
        "",
        f"{len(rows)} cords on {len({r.split('|')[1] for r in rows})} khipus.",
        "",
        "| cause | cords | meaning |",
        "|---|---|---|",
        *(f"| {c} | {causes[c]} | {CAUSES[c]} |" for c in CAUSES if causes[c]),
        "",
        "Notes",
        "- KH0004: the 2025-05-16 ChangeLog turned the khipu round (P1<->P6 ...); names and knots moved, the",
        "  Value column kept the old row order.",
        "- KH0016 p1s1: the loop cord carrying flags; its nine 1S knots are recorded at 10 each but Value is 0 -",
        "  plausibly deliberate (not a number), but the tokens then should not carry values.",
        "- KH0449: the KFG's own code table gives TF (tufted knot) value 1; the tokens carry 10 (and the OKR too).",
        "- KH0321 p90 / p140, KH0362 p10, KH0389 p38, KH0279 p99 / p100, KH0103 p1 / p5s2: late-2025 register",
        "  re-reads ('propose register shift') that changed Value but not (all) the knot tokens, or vice versa.",
        "- KH0631, KH0632, KH0657: recent Quave/KDB additions with one ChangeLog row; several cords off by one",
        "  cluster (e.g. KH0632 p11 457 vs 512 = an extra 5S,50 token).",
        "",
        "| khipu | cord | Value | knots | OKR | knot tokens | cause | note |",
        "|---|---|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    with open(os.path.join(HERE, "value_knot_conflicts.md"), "w") as f:
        f.write("\n".join(out))
    print(f"{len(rows)} cords; {dict(causes)}")


if __name__ == "__main__":
    main()
